def getShopColor(paletteIndex):
    """Return the current RGBA colour for a Club Shop palette index."""
    try:
        paletteIndex = int(paletteIndex)
    except (TypeError, ValueError):
        paletteIndex = 0
    pulser = SHOP_COLOR_PULSERS.get(paletteIndex)
    if pulser is not None:
        return pulser.getColor()
    if 0 <= paletteIndex < len(SHOP_COLORS):
        return SHOP_COLORS[paletteIndex]
    return SHOP_COLORS[paletteIndex % len(SHOP_COLORS)]


def isShopColorAnimated(paletteIndex):
    try:
        paletteIndex = int(paletteIndex)
    except (TypeError, ValueError):
        return False
    return paletteIndex in SHOP_COLOR_PULSERS

